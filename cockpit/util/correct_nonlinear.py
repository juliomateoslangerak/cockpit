# Correct data generated by a camera with a nonlinear response, using a
# map of the camera's response as measured using flatfield data.
#
# % correct_nonlinear.py -map map_file -suf suf -data file1 file2 ... fileN
# * -map map_file: Correction file generated by the "Response Map" experiment
#   in the OMX Cockpit program.
# * -suf suf: attach "suf" to corrected files. Defaults to "-linearized".
# * -data file1 ..: files to be corrected.
#
# The program will use the map_file file to map the response curve of the
# camera. Because we can't assume an overall linear response, we have no
# objective determination of the number of photons incident on the sensor.
# We must instead rely on the exposure time as a proxy for photons; the
# exposure time is stored in the extended header of the map_file. Thus we can
# map exposure time to average counts for each pixel. We must linearly
# interpolate between values for areas in which we do not have data.
#
# By making a linear fit for each pixel's response curve, we can force the data
# to linearity (generate a mapping of reported counts to linearized counts).
# I'm uncertain how closely this response corresponds to the true photon
# count; I wouldn't count on them bearing much resemblance.

import sys
import time

import numpy
import scipy.ndimage

from cockpit.util import datadoc


class Corrector:
    def __init__(self, exposure_times, map_data):
        """Set up the corrector from a set of response-curve images.

        Args:
            exposure_times (list): List of exposure times, one for each image.
            map_data (list): List of 2D numpy arrays mapping out the response
                curve.
        """
        ## Shape of an image.
        self.image_shape = map_data[0].shape

        ## In-order array of exposure times.
        self.exposure_times = numpy.array(exposure_times, dtype=numpy.float32)
        ## 3D array of pixel values for each pixel for each exposure time.
        self.image_data = numpy.array(map_data, dtype=numpy.float32)

        # Generate a linear fit for the data as a whole, so we can map any
        # exposure time to a single value in counts.
        self.slope, self.intercept = numpy.polyfit(
            self.exposure_times, map(numpy.mean, self.image_data), 1
        )
        print("Linear fit constructed")

        # Break our data up into clusters based on how far apart exposure times
        # are, and ensure that we have data for the very bottom and top of
        # the data range (assuming 0 and 2**16 are the limits).
        ## List of SubCorrectors covering all valid data ranges.
        self.sub_correctors = []
        exposure_spacing = numpy.median(
            self.exposure_times[1:] - self.exposure_times[:-1]
        )
        print("Calculate a median spacing of", exposure_spacing)
        cur_indices = []  # List of indices in the current cluster of data
        for i, exp_time in enumerate(self.exposure_times):
            if i == 0:
                # Can't do anything yet.
                cur_indices.append(i)
                continue
            prev_time = self.exposure_times[i - 1]
            if exp_time - prev_time > exposure_spacing * 10.0:
                # Large gap between exposure times; make new SubCorrectors.
                # One nonlinear for the current cluster, one linear for the gap.
                self.sub_correctors.append(
                    SubCorrector(
                        self.exposure_times[cur_indices],
                        self.image_data[cur_indices],
                        2,
                    )
                )
                cur_indices = [i - 1, i]
                self.sub_correctors.append(
                    SubCorrector(
                        self.exposure_times[cur_indices],
                        self.image_data[cur_indices],
                        2,
                    )
                )
                cur_indices = []
            cur_indices.append(i)

        # Clean up the remainder.
        self.sub_correctors.append(
            SubCorrector(
                self.exposure_times[cur_indices], self.image_data[cur_indices], 2
            )
        )
        # Ensure we have linear mapping to the bottom and top of the dataset,
        # by linearly extrapolating out to -maxint and maxint. We fit lines to
        # our bottom and top subcorrectors and extrapolate along their slopes.
        new_correctors = []
        for start_index, target in [(0, -(2 ** 16) + 1), (-1, (2 ** 16) - 1)]:
            corrector = self.sub_correctors[start_index]
            x_vals = corrector.exposure_times
            y_vals = corrector.image_data
            print(
                "Extrapolating with", x_vals, [numpy.median(v) for v in y_vals]
            )
            y_vals.shape = len(x_vals), numpy.product(self.image_shape)
            slopes, intercepts = numpy.polyfit(x_vals, y_vals, 1)
            # Restore our previous shape.
            y_vals.shape = len(x_vals), self.image_shape[0], self.image_shape[1]
            # Calculate extrapolated "exposure times" at the target.
            extrapolated = slopes * target + intercepts
            extrapolated.shape = self.image_shape

            images = [corrector.image_data[start_index]]
            times = [corrector.exposure_times[start_index]]
            if start_index == 0:
                images.insert(0, extrapolated)
                times.insert(0, -self.intercept / self.slope)
                print(
                    "Extrapolated to negative time at",
                    times[0],
                    numpy.median(images[0]),
                )
            else:
                images.append(extrapolated)
                times.append(target - self.intercept / self.slope)
            images = numpy.array(images)
            new_correctors.append(SubCorrector(times, images, 1))
        self.sub_correctors.extend(new_correctors)

    def correct(self, input_data):
        """Given an input data array (2D), return a corrected version.

        See this post for a non-vectorized version of this algorithm:
        http://mail.scipy.org/pipermail/scipy-user/2013-January/034051.html
        Each SubCorrector can only handle a certain range of inputs, so we must
        apply them iteratively to cover all the input data.
        """
        # Start out with "all uncorrected" data.
        result = numpy.ones(input_data.shape, dtype=numpy.float32) * -1
        for corrector in self.sub_correctors:
            exposures = corrector.correct(input_data)
            valid_indices = numpy.where(exposures != -1)
            result[valid_indices] = exposures[valid_indices]
            if numpy.all(result != -1):
                # All done
                break
        if numpy.any(result == -1):
            # We failed to correct some of the pixels. This should only be an
            # issue if our response map is basically flat at one end (the
            # low end, most likely), such that our extrapolation of the
            # curve doesn't cover the camera's full range. For example, if our
            # map of a pixel flattens at the bottom at 108 counts, then our
            # extrapolation past the end of the map data will not go below 108,
            # and if the pixel actually reads 107 then we can't correct it.
            bad_pixels = numpy.where(result == -1)
            print("Failed to correct %d pixels" % len(bad_pixels[0]))
            for x, y in zip(*bad_pixels):
                print(
                    "(%d, %d): %d, %s"
                    % (
                        x,
                        y,
                        input_data[x, y],
                        ", ".join(
                            [c.describe(x, y) for c in self.sub_correctors]
                        ),
                    )
                )
            # Is this really the best thing to do here? It seems better than
            # just leaving -1 in the result, which will get wrapped to 65535
            # when we save it...
            result[bad_pixels] = input_data[bad_pixels]
        # Convert from "exposure time" to "counts", purely to give the user
        # numbers in the range they're used to dealing with from the camera.
        return result * self.slope + self.intercept


class SubCorrector:
    """This class is a subcontractor to the Corrector class, responsible for
    linearizing a portion of the data range.

    We do this because it's expected that the response curve map is dense where
    the curve is nonlinear and sparse otherwise. Our correcting system requires
    us to have a synthetic uniform sampling of the response curve, which gets
    prohibitive in memory usage if we try to do it for the entire possible data
    range, so we split it up into sections.
    """

    def __init__(self, exposure_times, images, sample_rate=1):
        """Set up a corrector valid for a range of exposure times.

        Args:
            exposure_times (list): List of exposure times we are valid for.
            images (list): List of 2D image arrays of corresponding exposure
                times.
            sample_rate (int): Amount of supersampling we should perform when we
                create a uniform sampling of the image data.
        """
        print(
            "Making subcontractor with times/median values",
            "\n".join(
                [
                    str((t, numpy.median(d)))
                    for t, d in zip(exposure_times, images)
                ]
            ),
        )
        self.exposure_times = exposure_times
        self.image_data = images
        self.image_shape = images.shape[1:]

        # We now need to uniformly sample our input data so that we can
        # efficiently invert the exposure time -> counts function. See
        # thread starting here:
        # http://mail.scipy.org/pipermail/scipy-user/2013-January/034032.html
        # (continues on into February)
        self.min_vals = self.image_data.min(axis=0)
        self.max_vals = self.image_data.max(axis=0)

        self.num_samples = len(self.image_data) * sample_rate
        sampled_shape = (
            self.num_samples,
            self.image_shape[0],
            self.image_shape[1],
        )
        self.uniform_data = numpy.zeros(sampled_shape, dtype=numpy.float32)
        self.uniform_exposures = numpy.zeros(sampled_shape, dtype=numpy.float32)
        for i in range(self.image_shape[0]):
            for j in range(self.image_shape[1]):
                self.uniform_data[:, i, j] = numpy.linspace(
                    self.min_vals[i, j], self.max_vals[i, j], self.num_samples
                )
                self.uniform_exposures[:, i, j] = numpy.interp(
                    self.uniform_data[:, i, j],
                    self.image_data[:, i, j],
                    self.exposure_times,
                )

    def correct(self, input_data):
        """Given an input 2D array, linearize it so that its values are in
        terms of "exposure time" instead of counts.

        If a value is outside the range we can handle, then return -1 for that
        pixel.
        """
        indices = (
            (self.num_samples - 1)
            * (input_data - self.min_vals)
            / (self.max_vals - self.min_vals)
        )
        map_input = numpy.zeros((3, self.image_shape[0], self.image_shape[1]))
        map_input[:1] = indices
        map_input[1:] = numpy.indices(self.image_shape)
        exposures = scipy.ndimage.map_coordinates(
            self.uniform_exposures, map_input, order=1, cval=-1
        )
        return exposures

    def describe(self, x, y):
        """Return a description of our mapping for the specified pixel."""
        return "(%.2f @ %.2f, %.2f @ %.2f)" % (
            self.uniform_data[0, x, y],
            self.exposure_times[0],
            self.uniform_data[-1, x, y],
            self.exposure_times[-1],
        )

    def __repr__(self):
        return "<SubCorrector with range (%.2f %d, %.2f %d)>" % (
            self.exposure_times[0],
            numpy.median(self.uniform_data[0]),
            self.exposure_times[-1],
            numpy.median(self.uniform_data[-1]),
        )


if __name__ == "__main__":
    map_file = None
    data_files = []
    suffix = "-linearized"
    cur_item = None
    i = 1
    while i < len(sys.argv):
        arg = sys.argv[i]
        if arg == "-map":
            i += 1
            map_file = sys.argv[i]
        elif arg == "-data":
            cur_item = data_files
        elif arg == "-suf":
            i += 1
            suffix = sys.argv[i]
        else:
            cur_item.append(arg)
        i += 1

    # Load the map file and separate out the exposure times from the individual
    # averaged images.
    exp_time_to_data = {}
    map_file = datadoc.DataDoc(map_file)
    for z in range(map_file.size[2]):
        exposure_time = map_file.extended_header_floats[0, 0, z, 0, 0]
        data = map_file.image_array[0, 0, z]
        exp_time_to_data[exposure_time] = data

    exp_data_pairs = sorted(exp_time_to_data.items())
    exposure_times = [e[0] for e in exp_data_pairs]
    map_data = [e[1] for e in exp_data_pairs]

    print("Loaded exposure time / mean value pairs:")
    print("\n".join(map(str, [(t, numpy.mean(d)) for t, d in exp_data_pairs])))

    start = time.time()
    corrector = Corrector(exposure_times, map_data)
    time_to_make = time.time() - start
    correction_times = []
    for filename in data_files:
        input_data = datadoc.DataDoc(filename).image_array
        #    print ("Loading",filename,"initial stats",input_data.min(),input_data.max(),numpy.median(input_data),numpy.std(input_data))
        result = numpy.zeros(input_data.shape, dtype=numpy.float32)
        sub_start = time.time()
        for wavelength in range(input_data.shape[0]):
            for timepoint in range(input_data.shape[1]):
                for z in range(input_data.shape[2]):
                    print(filename, timepoint, z)
                    result[wavelength, timepoint, z] = corrector.correct(
                        input_data[wavelength, timepoint, z]
                    )
        correction_times.append(time.time() - sub_start)
        datadoc.write_data_as_mrc(result, filename + suffix)
    #    print ("%s: %.2f, %.2f, %.2f, %.2f" % (filename, result.min(), result.max(), numpy.mean(result), numpy.std(result)))

    overall_time = time.time() - start
    print(
        "Initialization took %.2f; correction took on average %.2f; overall %.2f for %d files"
        % (
            time_to_make,
            numpy.mean(correction_times),
            overall_time,
            len(data_files),
        )
    )
